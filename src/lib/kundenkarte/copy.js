export const COPY = Object.freeze({ de, en, fr, it });

/** Texte der Sprache, Standard Deutsch. */
export function kundenkarteCopy(locale) {
  return COPY[locale] || COPY.de;
}

/** "{vorname}"-Platzhalter füllen. */
export function fill(text, values = {}) {
  return String(text).replace(/\{(\w+)\}/g, (m, k) => (k in values ? String(values[k]) : m));
}

/** Alle sichtbaren Texte einer Sprache als flache Liste (Wortlisten-Test). */
export function allTexts(locale) {
  const out = [];
  (function walk(v) {
    if (typeof v === "string") out.push(v);
    else if (Array.isArray(v)) v.forEach(walk);
    else if (v && typeof v === "object") Object.values(v).forEach(walk);
  })(kundenkarteCopy(locale));
  return out;
}
