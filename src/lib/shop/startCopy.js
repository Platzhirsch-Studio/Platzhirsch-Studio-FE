export const SHOP_START_COPY = Object.freeze({ de, en, fr, it });

/** Texte einer Sprache (Fallback Deutsch). */
export const startCopy = (locale) => SHOP_START_COPY[locale] || SHOP_START_COPY.de;

/** Plural-Bezeichnung einer Accessoire-Kategorie oder der Fallback (Katalog-Label). */
export const kategoriePlural = (locale, slug, fallback = slug) => startCopy(locale).kategorien?.[slug] || fallback;

/** „Österreich und Deutschland“ / „Austria, Germany and …“ */
export function laenderListe(codes, locale) {
  const c = startCopy(locale);
  const names = codes.map((k) => c.laender[k] || k);
  if (names.length < 2) return names.join("");
  return `${names.slice(0, -1).join(", ")} ${c.und} ${names[names.length - 1]}`;
}
