export const SHOP_COPY = Object.freeze({ de: { ...de, ...ui.de }, en: { ...en, ...ui.en }, fr: { ...fr, ...ui.fr }, it: { ...it, ...ui.it } });
/** Platzhalter {name}/{n} füllen (Client und Server). */
export const fillCopy = (s, vars = {}) => String(s ?? "").replace(/\{(\w+)\}/g, (m, k) => (vars[k] != null ? String(vars[k]) : m));
export const shopCopy = (locale) => SHOP_COPY[locale] || de;
/** Schlüssel der Produkt-Insel AddToCart inkl. Mini-Warenkorb. */
export const ADD_TO_CART_KEYS = Object.freeze(["inCart", "added", "reserve", "variant", "qty", "cartTitle", "drawerTitle", "drawerAdded", "continueShopping", "toCheckout", "subtotal", "subtotalNote", "cartFull", "qtyMax", "loadingPrices", "pricesError", "retry", "close", "inclVat", "inclVatRate", "basePrice"]);
/** Teilmenge für eine Client-Insel (nur die nötigen Schlüssel). */
export const pickCopy = (locale, keys) => Object.fromEntries(keys.map((k) => [k, shopCopy(locale)[k]]));
