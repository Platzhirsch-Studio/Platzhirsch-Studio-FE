import "server-only";
import { familySummary, normalizeFamily } from "./normalize.js";
import { buildTemplates, thumbOf } from "./templates.js";
import { mergeCovers } from "./covers.js";
import { MINOTTI_DATA_CONSENT } from "./consent.js";
import { NEUTRAL_DEFAULT, NEUTRAL_FILES } from "./neutral-data.js";

// Release-Rat R2 (neuland P0-1): without written consent (MINOTTI_DATA_CONSENT,
// ./consent.js) the catalogue holds only the neutral planning types of
// ./neutral-data.js. The Minotti research files are then never imported – the
// dynamic import below sits behind the switch, so no Minotti record reaches the
// page HTML, the catalogue route or the browser bundle.
async function source() {
  if (!MINOTTI_DATA_CONSENT) return { files: NEUTRAL_FILES, covers: {} };
  const m = await import("./minotti-data.js");
  return { files: m.MINOTTI_FILES, covers: m.COVERS || {} };
}

// Server catalogue of all Minotti families (research files in ./minotti).
// Normalised once per server process and kept in memory (≈ 4 MB of JSON).
// The browser only ever gets the index (model picker) and the ONE family that
// is being planned (page props or GET /de/sofaplaner/katalog/<slug>).
//
// Deployment (QM Abnahme R3): the files come in through static imports
// (minotti-data.js, generated by tools/build-catalog-index.mjs), so they are
// bundled with the server code – no fs access at runtime, nothing for output
// file tracing to miss, no outputFileTracingIncludes needed.

let cache = null;
let pending = null;
/** Loads the catalogue once per server process. Call before the sync helpers below. */
export async function ensureCatalog() {
  if (cache) return cache;
  pending ||= source().then(({ files, covers }) => build(files, covers));
  return pending;
}
function load() {
  if (!cache) throw new Error("[sofaplaner] ensureCatalog() vor dem Zugriff aufrufen");
  return cache;
}
function build(files, covers) {
  if (cache) return cache;
  const families = new Map();
  for (const [file, raw] of files) {
    try {
      // structuredClone: normalisation must never touch the shared module object
      const fam = normalizeFamily(structuredClone(raw));
      const merged = mergeCovers(fam, covers);
      fam.options.cover = { ...fam.options.cover, collections: merged.collections, brand: merged.brand };
      families.set(fam.slug, fam);
    } catch (err) {
      console.error(`[sofaplaner] ${file} konnte nicht gelesen werden`, err);
    }
  }
  cache = { families, templates: new Map() };
  return cache;
}

export const DEFAULT_FAMILY = MINOTTI_DATA_CONSENT ? "connery" : NEUTRAL_DEFAULT;

export function getFamily(slug) {
  return load().families.get(slug) || null;
}

export function templatesFor(slug) {
  const c = load();
  if (!c.templates.has(slug)) {
    const fam = c.families.get(slug);
    c.templates.set(slug, fam ? buildTemplates(fam) : []);
  }
  return c.templates.get(slug);
}

/** Family as sent to the browser: element sources de-duplicated against the family list. */
export function clientFamily(slug) {
  const fam = getFamily(slug);
  if (!fam) return null;
  const famSources = new Set(fam.sources);
  // smaller page payload: drop null/false scalars and the research key (arrays stay)
  const elements = fam.elements.map((e) => {
    const out = { sources: e.sources.filter((u) => !famSources.has(u)) };
    for (const [k, v] of Object.entries(e)) {
      if (k === "sources" || k === "srcCode" || v === null || v === false) continue;
      out[k] = v;
    }
    return out;
  });
  return { ...fam, elements, templates: templatesFor(slug) };
}

let indexCache = null;
/** Model picker index, sorted by name, with a small top-view thumbnail. */
export function familyIndex() {
  if (indexCache) return indexCache;
  const { families } = load();
  indexCache = [...families.values()]
    .map((f) => {
      const t = templatesFor(f.slug);
      const pick = t.find((x) => x.key === "ecke-links") || t.find((x) => x.key === "gerade") || t[0];
      const map = new Map(f.elements.map((e) => [e.code, e]));
      // slim index for the page (QM R1 P2-6): no kinds list, thumbnails rounded to whole cm
      const { kinds: _kinds, ...sum } = familySummary(f);
      const thumb = pick ? thumbOf(pick.items, (c) => map.get(c)).map((i) => ({ ...i, x: Math.round(i.x), y: Math.round(i.y), w: Math.round(i.w), d: Math.round(i.d) })) : [];
      // seat width per place (front silhouette on the model card, R2 neuland P1-5)
      const seat = f.elements.find((e) => e.role === "mid" && e.module)?.module ?? null;
      return { ...sum, forms: t.map((x) => x.key), thumb, seat };
    })
    .sort((a, b) => a.name.localeCompare(b.name, "de"));
  return indexCache;
}
