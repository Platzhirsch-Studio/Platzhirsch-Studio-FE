// Builds src/lib/sofaplaner/minotti-data.js: one static import per research
// file in src/lib/sofaplaner/minotti/*.json (sorted like readdirSync).
//
// Why (QM Sofaplaner Abnahme R3, "Deployment"): catalog.server.js used to read
// the folder with fs.readdirSync(process.cwd() + …). Output file tracing
// cannot follow a directory listing, so a standalone/serverless deployment
// could ship without the model data. Static imports are bundled into the
// server chunks of the Sofaplaner routes – nothing has to be traced or copied,
// and next.config.js needs no outputFileTracingIncludes.
//
// Run after adding, renaming or removing a family file:
//   node src/lib/sofaplaner/tools/build-catalog-index.mjs
// tests/unit/sofaplaner-feinschliff.test.mjs fails if the index is out of date.

import fs from "node:fs";
import path from "node:path";

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Z]:)/, "$1")), "..");
const files = fs.readdirSync(path.join(root, "minotti")).filter((f) => f.endsWith(".json")).sort();
const lines = [
  "// GENERATED by src/lib/sofaplaner/tools/build-catalog-index.mjs – do not edit by hand.",
  "// Static imports of all Minotti research files, so the data is bundled with the",
  "// server code (no fs access, no output file tracing needed).",
  ...files.map((f, i) => `import f${i} from "./minotti/${f}";`),
  "",
  "/** [file name, parsed research JSON] for every family, sorted by file name. */",
  "export const MINOTTI_FILES = [",
  ...files.map((f, i) => `  ["${f}", f${i}],`),
  "];",
  "",
  'export { default as COVERS } from "./minotti-covers.json";',
  "",
];
fs.writeFileSync(path.join(root, "minotti-data.js"), lines.join("\n"));
console.log(`minotti-data.js: ${files.length} Familien`);
