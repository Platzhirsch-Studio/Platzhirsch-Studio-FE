/** Wert unter "a.b.c" in einem Objekt (oder undefined). */
function pick(obj, key) {
  return String(key)
    .split(".")
    .reduce((o, k) => (o && typeof o === "object" ? o[k] : undefined), obj);
}

/**
 * Text der Seite: zuerst die Messages (badWellness.<key>, sobald übernommen),
 * sonst die Tabelle der Sprache, sonst Deutsch.
 * @param {string} locale
 * @param {string} key   z. B. "bad.title" oder "marke.aquaviaspa.text"
 * @param {{has?: Function, raw?: Function}} [t]  next-intl-Übersetzer OHNE Namespace
 */
export function bwText(locale, key, t) {
  const full = `${BW_NS}.${key}`;
  try {
    if (t && typeof t.has === "function" && t.has(full)) {
      const v = t.raw(full);
      if (typeof v === "string" && v) return v;
    }
  } catch {
    // Messages ohne diesen Schlüssel: Tabelle.
  }
  const v = pick(BW_TEXT[locale] || BW_TEXT.de, key);
  return typeof v === "string" ? v : pick(BW_TEXT.de, key) ?? "";
}
