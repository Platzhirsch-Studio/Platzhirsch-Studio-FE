/** Alle Texte als flache Liste (Unit-Test: keine Superlative, keine Ausrufezeichen, Umlaute). */
export function alleTexte() {
  const out = [];
  const lauf = (v) => {
    if (typeof v === "string") out.push(v);
    else if (typeof v === "function") {
      try {
        const r = v(2, "X", "Y");
        if (typeof r === "string") out.push(r);
      } catch {
        // nur Strings zählen
      }
    } else if (v && typeof v === "object") for (const x of Object.values(v)) lauf(x);
  };
  for (const t of [GRUSS, ZENTRALE, KOPFZAHLEN, STUFEN_PROJEKT, PROJEKTART, NAECHSTER_SCHRITT, FRISTEN, AUFGABEN, VERWALTUNG, EINSTELLUNGEN, BENACHRICHTIGUNGEN, SUCHE, DRUCKZENTRALE, PROTOKOLL, GERAETE, BENUTZER]) lauf(t);
  return out;
}
