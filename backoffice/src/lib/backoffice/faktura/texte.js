/** {anrede_brief} aus PH Kontakt (R-18). */
export function anredeBrief({ anrede, vorname, nachname, kontaktart, firma } = {}) {
  if (kontaktart === "Geschaeft" || kontaktart === "Firma" || (firma && !nachname)) return "Sehr geehrte Damen und Herren";
  if (anrede === "Frau" && nachname) return `Sehr geehrte Frau ${nachname}`;
  if (anrede === "Herr" && nachname) return `Sehr geehrter Herr ${nachname}`;
  const name = [vorname, nachname].filter(Boolean).join(" ");
  return name ? `Guten Tag ${name}` : "Guten Tag";
}

/** Platzhalter {x} ersetzen; fehlende bleiben sichtbar. */
export function fuelle(vorlage, werte = {}) {
  return String(vorlage || "").replace(/\{([a-z_]+)\}/g, (m, k) => (werte[k] !== undefined && werte[k] !== null && werte[k] !== "" ? String(werte[k]) : m));
}

