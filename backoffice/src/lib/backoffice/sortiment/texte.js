/** Anzeigetext eines Rohwerts (Glossar-Gruppe), Rückfall: Rohwert mit Umlauten, leer → „–“. */
export function anzeigeWert(gruppe, wert) {
  if (wert === null || wert === undefined || wert === "") return "–";
  const g = GLOSSAR[gruppe];
  if (g && Object.prototype.hasOwnProperty.call(g, wert)) return g[wert];
  return umlaute(String(wert));
}

const UMLAUT_AUSNAHMEN = /^(Queue|Quelle|Steuer|Dauer|neue?)$/i;
/** Einfache Umlaut-Rückwandlung für Rückfälle (ae/oe/ue nach Konsonant; „ue“ nach „q“ bleibt). */
export function umlaute(text) {
  return String(text)
    .split(/(\s+)/)
    .map((w) => (UMLAUT_AUSNAHMEN.test(w) ? w : w.replace(/([^aeiouqAEIOUQ])ae/g, "$1ä").replace(/([^aeiouqAEIOUQ])oe/g, "$1ö").replace(/([^aeiouqAEIOUQ])ue/g, "$1ü").replace(/^Ae/, "Ä").replace(/^Oe/, "Ö").replace(/^Ue/, "Ü")))
    .join("");
}

