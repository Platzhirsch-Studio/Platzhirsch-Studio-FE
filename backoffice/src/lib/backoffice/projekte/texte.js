export function statusText(doctype, wert) {
  if (wert === null || wert === undefined || wert === "") return "";
  const w = String(wert);
  return STATUS_ANZEIGE[doctype]?.[w] ?? STATUS_ANZEIGE["*"][w] ?? w;
}

