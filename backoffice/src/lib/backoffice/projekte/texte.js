/** Stunden als „7,5“ ohne Nachkommanullen. */
export function fmtH(h) {
  const n = Math.round(Number(h || 0) * 100) / 100;
  return n.toLocaleString("de-DE", { maximumFractionDigits: 2 });
}

/** Ersetzt {platzhalter} – fehlende bleiben sichtbar (Informieren meldet sie). */
export function fuelle(text, werte = {}) {
  return String(text || "").replace(/\{(\w+)\}/g, (m, k) => (werte[k] !== undefined && werte[k] !== null && werte[k] !== "" ? String(werte[k]) : m));
}
