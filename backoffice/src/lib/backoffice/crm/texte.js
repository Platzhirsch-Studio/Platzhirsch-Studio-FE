/** Statt Fehlercode ein Satz. */
export function fehlerText(code, message) {
  if (message && !/[a-z_]+\.[a-z_]+|Traceback|DocType|ph_/.test(message)) return message;
  return CRM_TEXTE.fehler[code] || CRM_TEXTE.fehler.unbekannt;
}

