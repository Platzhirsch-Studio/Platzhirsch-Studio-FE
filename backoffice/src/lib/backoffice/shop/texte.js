/** Verlaufszeile des Servers in Nutzersprache (§ 2.6); Unbekanntes unverändert. */
export function verlaufText(text) {
  let t = String(text || "");
  for (const [re, ersatz] of T.verlauf) t = t.replace(re, ersatz);
  return t;
}

/** Eine Mail-Adresse für Toasts kürzen: „huber@beispiel.invalid“ → „h…@beispiel.invalid“ (keine Personendaten im Toast). */
export function mailKurz(mail) {
  const m = /^([^@]+)@(.+)$/.exec(String(mail || ""));
  return m ? `${m[1].charAt(0)}…@${m[2]}` : "den Kunden";
}

