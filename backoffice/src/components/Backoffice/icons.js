/** „triangle-alert“ → „TriangleAlert“, „building-2“ → „Building2“. */
export function iconName(name) {
  if (!name) return "Info";
  if (ICONS[name]) return name;
  const pascal = String(name)
    .split("-")
    .map((t) => t.charAt(0).toUpperCase() + t.slice(1))
    .join("");
  return ICONS[pascal] ? pascal : "Info";
}

/** Strichstärke aus der Größenklasse: bis size-6 (24 px) 1.75 wie in der Lounge, ab size-8 1.5. */
export function strichFuer(className = "") {
  const m = /(?:^|\s)size-(\d+(?:\.\d+)?)(?:\s|$)/.exec(className);
  const s = m ? Number(m[1]) : 4;
  if (s >= 8) return 1.5;
  return 1.75;
}

/**
 * <Icon name="Hammer" className="size-4" /> – unbekannter Name → Info.
 * Dekorativ (aria-hidden), außer `label` ist gesetzt: dann role="img" mit aria-label.
 */
export function Icon({ name, className = "size-4", label, strokeWidth, ...rest }) {
  const C = ICONS[iconName(name)] || Info;
  const a11y = label ? { role: "img", "aria-label": label } : { "aria-hidden": "true" };
  return <C {...a11y} className={className} strokeWidth={strokeWidth ?? strichFuer(className)} {...rest} />;
}
